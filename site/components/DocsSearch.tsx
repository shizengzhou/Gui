'use client';

import type { KeyboardEvent as ReactKeyboardEvent } from 'react';
import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { useRouter } from 'next/navigation';
import { Icon } from '@/components/Icons';

type Lang = 'zh' | 'en';
type PageLabel = { zh: string; en: string };
type Entry = {
  href: string;
  lang: Lang;
  id: string;
  page: PageLabel;
  heading: string;
  text: string;
};

const MAX_RESULTS = 12;

function currentLang(): Lang {
  return document.documentElement.dataset.lang === 'en' ? 'en' : 'zh';
}

function score(entry: Entry, query: string, lang: Lang): number {
  const heading = entry.heading.toLowerCase();
  const page = entry.page[lang].toLowerCase();
  let value = 0;
  if (heading === query) value += 140;
  else if (heading.startsWith(query)) value += 100;
  else if (heading.includes(query)) value += 70;
  if (page === query) value += 90;
  else if (page.includes(query)) value += 40;
  if (entry.text.toLowerCase().includes(query)) value += 25;
  return value;
}

// Show the text around the first hit, or the opening of the section.
function snippet(entry: Entry, query: string): string {
  const text = entry.text;
  const needle = query.trim().toLowerCase();
  const at = needle ? text.toLowerCase().indexOf(needle) : -1;
  if (at < 0) return text.length > 120 ? text.slice(0, 120) + '…' : text;
  const start = Math.max(0, at - 40);
  const end = Math.min(text.length, start + 140);
  return (start > 0 ? '…' : '') + text.slice(start, end) + (end < text.length ? '…' : '');
}

function Highlight({ text, query }: { text: string; query: string }) {
  const needle = query.trim();
  const at = needle ? text.toLowerCase().indexOf(needle.toLowerCase()) : -1;
  if (at < 0) return <>{text}</>;
  return (
    <>
      {text.slice(0, at)}
      <mark>{text.slice(at, at + needle.length)}</mark>
      {text.slice(at + needle.length)}
    </>
  );
}

// The sidebar's "Search docs" row and the Ctrl-K dialog behind it. The index is
// generated by scripts/gen-search-index.mjs and fetched on first open so the
// docs pages do not carry it in their initial payload.
export default function DocsSearch() {
  const router = useRouter();
  const [lang, setLang] = useState<Lang>('zh');
  const [modifier, setModifier] = useState('Ctrl');
  const [open, setOpen] = useState(false);
  const [query, setQuery] = useState('');
  const [active, setActive] = useState(0);
  const [entries, setEntries] = useState<Entry[] | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  // Follow the <html data-lang> toggle so the trigger and results match the page.
  useEffect(() => {
    const read = () => setLang(currentLang());
    read();
    const observer = new MutationObserver(read);
    observer.observe(document.documentElement, { attributes: true, attributeFilter: ['data-lang'] });
    if (/Mac|iPhone|iPad/.test(navigator.platform)) setModifier('⌘');
    return () => observer.disconnect();
  }, []);

  const openDialog = useCallback(() => {
    setLang(currentLang());
    setQuery('');
    setActive(0);
    setOpen(true);
    void import('@/lib/search-index.json').then((mod) => setEntries(mod.default.entries as unknown as Entry[]));
  }, []);

  const closeDialog = useCallback(() => {
    setOpen(false);
    setQuery('');
  }, []);

  // Ctrl-K (Cmd-K) opens the dialog from anywhere in the docs; Escape closes it.
  useEffect(() => {
    const onKey = (event: KeyboardEvent) => {
      if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === 'k') {
        event.preventDefault();
        if (open) closeDialog();
        else openDialog();
      } else if (event.key === 'Escape' && open) {
        closeDialog();
      }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [open, openDialog, closeDialog]);

  useEffect(() => {
    if (!open) return;
    const timer = window.setTimeout(() => inputRef.current?.focus(), 0);
    const overflow = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
    return () => {
      window.clearTimeout(timer);
      document.body.style.overflow = overflow;
    };
  }, [open]);

  const results = useMemo(() => {
    const pool = (entries ?? []).filter((entry) => entry.lang === lang);
    const text = query.trim().toLowerCase();
    if (!text) return pool.filter((entry) => entry.id === '');
    return pool
      .map((entry) => ({ entry, value: score(entry, text, lang) }))
      .filter((item) => item.value > 0)
      .sort((a, b) => b.value - a.value)
      .slice(0, MAX_RESULTS)
      .map((item) => item.entry);
  }, [entries, lang, query]);

  useEffect(() => setActive(0), [query, lang]);
  useEffect(() => {
    setActive((value) => Math.min(value, Math.max(0, results.length - 1)));
  }, [results]);

  function go(entry: Entry) {
    const url = entry.id ? `${entry.href}#${entry.id}` : entry.href;
    closeDialog();
    if (window.location.pathname === entry.href) {
      if (entry.id) document.getElementById(entry.id)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
      else window.scrollTo({ top: 0, behavior: 'smooth' });
      window.history.replaceState(null, '', url);
    } else {
      router.push(url);
    }
  }

  function onInputKeyDown(event: ReactKeyboardEvent<HTMLInputElement>) {
    if (event.key === 'ArrowDown') {
      event.preventDefault();
      setActive((value) => (results.length ? (value + 1) % results.length : 0));
    } else if (event.key === 'ArrowUp') {
      event.preventDefault();
      setActive((value) => (results.length ? (value - 1 + results.length) % results.length : 0));
    } else if (event.key === 'Enter') {
      event.preventDefault();
      const chosen = results[active];
      if (chosen) go(chosen);
    }
  }

  return (
    <>
      <button type="button" className="doc-search" onClick={openDialog}>
        <Icon name="search" />
        <span className="doc-search-label">{lang === 'en' ? 'Search docs' : '搜索文档'}</span>
        <kbd>{modifier} K</kbd>
      </button>

      {open ? (
        <div
          className="search-overlay"
          onMouseDown={(event) => {
            if (event.target === event.currentTarget) closeDialog();
          }}
        >
          <div className="search-dialog" role="dialog" aria-modal="true" aria-label={lang === 'en' ? 'Search docs' : '搜索文档'}>
            <div className="search-field">
              <Icon name="search" />
              <input
                ref={inputRef}
                value={query}
                onChange={(event) => setQuery(event.target.value)}
                onKeyDown={onInputKeyDown}
                placeholder={lang === 'en' ? 'Search docs…' : '搜索文档…'}
                aria-label={lang === 'en' ? 'Search docs' : '搜索文档'}
                autoComplete="off"
                spellCheck={false}
              />
              <kbd>Esc</kbd>
            </div>
            <ul className="search-results">
              {entries === null ? (
                <li className="search-empty">{lang === 'en' ? 'Loading…' : '正在载入…'}</li>
              ) : results.length === 0 ? (
                <li className="search-empty">{lang === 'en' ? 'No results.' : '没有匹配的结果。'}</li>
              ) : (
                results.map((entry, index) => (
                  <li key={`${entry.href}-${entry.id}-${entry.heading}`}>
                    <button
                      type="button"
                      className={'search-result' + (index === active ? ' active' : '')}
                      onMouseEnter={() => setActive(index)}
                      onClick={() => go(entry)}
                    >
                      {entry.id ? <span className="search-result-page">{entry.page[lang]}</span> : null}
                      <span className="search-result-title">
                        <Highlight text={entry.id ? entry.heading : entry.page[lang]} query={query} />
                      </span>
                      {entry.text ? (
                        <span className="search-result-snippet">
                          <Highlight text={snippet(entry, query)} query={query} />
                        </span>
                      ) : null}
                    </button>
                  </li>
                ))
              )}
            </ul>
          </div>
        </div>
      ) : null}
    </>
  );
}
